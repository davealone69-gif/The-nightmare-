    def test_verifier_rejects_nested_symlinks_and_non_regular_entries(self) -> None:
        for entry_kind in ("file symlink", "directory symlink", "FIFO"):
            with self.subTest(entry_kind=entry_kind), tempfile.TemporaryDirectory() as temporary:
                parent = Path(temporary)
                source = parent / "source"
                source.mkdir()
                self._make_project(source)
                output = parent / "out"
                result = export_project(source, output)
                nested = result["folder"] / "nested"
                nested.mkdir()
                entry = nested / "unexpected"

                if entry_kind == "file symlink":
                    outside = parent / "outside.txt"
                    outside.write_text("must not be hashed through the link\n", encoding="utf-8")
                    entry.symlink_to(outside)
                    original_read_bytes = Path.read_bytes

                    def forbid_link_read(path):
                        if path == entry:
                            raise AssertionError("verifier read through a symlink")
                        return original_read_bytes(path)

                    with mock.patch.object(Path, "read_bytes", forbid_link_read):
                        with self.assertRaisesRegex(ValueError, "symlink or non-regular"):
                            verify_export_pair(output)
                elif entry_kind == "directory symlink":
                    outside = parent / "outside-directory"
                    outside.mkdir()
                    (outside / "secret.txt").write_text("outside\n", encoding="utf-8")
                    entry.symlink_to(outside, target_is_directory=True)
                    with self.assertRaisesRegex(ValueError, "symlink or non-regular"):
                        verify_export_pair(output)
                else:
                    os.mkfifo(entry)
                    with self.assertRaisesRegex(ValueError, "symlink or non-regular"):
                        verify_export_pair(output)

    def test_staged_files_and_publication_directories_are_fsynced_in_order(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            parent = Path(temporary)
            source = parent / "source"
            source.mkdir()
            self._make_project(source)
            output = parent / "out"
            events = []
            synced_files = []
            original_file_sync = portable_export._fsync_file
            original_directory_sync = portable_export._fsync_directory
            original_rename = portable_export._rename_noreplace

            def file_sync(path):
                synced_files.append(Path(path).name)
                return original_file_sync(path)

            def directory_sync(path):
                events.append(("directory", Path(path)))
                return original_directory_sync(path)

            def rename(source_path, destination_path):
                events.append(("rename", Path(destination_path).name))
                return original_rename(source_path, destination_path)

            with mock.patch("tools.export_portable._fsync_file", side_effect=file_sync):
                with mock.patch(
                    "tools.export_portable._fsync_directory", side_effect=directory_sync
                ):
                    with mock.patch(
                        "tools.export_portable._rename_noreplace", side_effect=rename
                    ):
                        export_project(source, output)

            self.assertIn("run.sh", synced_files)
            self.assertIn(PORTABLE_NAME + ".zip", synced_files)
            self.assertGreaterEqual(sum(1 for event in events if event == ("directory", output)), 5)
            for published_name in (PORTABLE_NAME, PORTABLE_NAME + ".zip"):
                index = events.index(("rename", published_name))
                self.assertEqual(events[index + 1][0], "directory")
                self.assertTrue(events[index + 1][1].name.startswith(".nightmare-export-"))
                self.assertEqual(events[index + 2], ("directory", output))

