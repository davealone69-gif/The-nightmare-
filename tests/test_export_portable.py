    def test_concurrent_export_refuses_second_writer_without_partial_output_or_retry_blockage(
        self,
    ) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            parent = Path(temporary)
            source = parent / "source"
            source.mkdir()
            self._make_project(source)
            output = parent / "out"
            writer_entered = threading.Event()
            release_writer = threading.Event()
            second_done = threading.Event()
            first_outcomes = []
            second_outcomes = []
            original_write_bundle = _write_bundle

            def paused_write_bundle(files: object, project_root: Path, destination: Path) -> None:
                destination.mkdir(parents=True)
                partial = destination / "incomplete"
                partial.write_text("staging only", encoding="utf-8")
                writer_entered.set()
                if not release_writer.wait(5):
                    raise TimeoutError("test did not release the first exporter")
                partial.unlink()
                destination.rmdir()
                original_write_bundle(files, project_root, destination)

            def run_export(outcomes: list, completed=None) -> None:
                try:
                    outcomes.append(export_project(source, output))
                except BaseException as exc:
                    outcomes.append(exc)
                finally:
                    if completed is not None:
                        completed.set()

            with mock.patch("tools.export_portable._write_bundle", side_effect=paused_write_bundle):
                first = threading.Thread(target=run_export, args=(first_outcomes,))
                second = None
                first.start()
                try:
                    self.assertTrue(
                        writer_entered.wait(2), "first exporter never reached staging"
                    )
                    second = threading.Thread(
                        target=run_export, args=(second_outcomes, second_done)
                    )
                    second.start()
                    self.assertTrue(
                        second_done.wait(2),
                        "concurrent export blocked instead of refusing immediately",
                    )
                    self.assertEqual(len(second_outcomes), 1)
                    self.assertIsInstance(second_outcomes[0], FileExistsError)
                    self.assertIn(
                        "another portable export is in progress",
                        str(second_outcomes[0]),
                    )
                    self.assertFalse((output / PORTABLE_NAME).exists())
                    self.assertFalse((output / (PORTABLE_NAME + ".zip")).exists())
                    self.assertFalse((output / TRANSACTION_NAME).exists())
                    self.assertEqual(
                        len(list(output.glob(".nightmare-export-*/the-nightmare-portable/incomplete"))),
                        1,
                    )
                finally:
                    release_writer.set()
                    first.join(timeout=5)
                    if second is not None:
                        second.join(timeout=5)

            self.assertFalse(first.is_alive(), "first exporter did not finish")
            self.assertEqual(len(first_outcomes), 1)
            self.assertIsInstance(first_outcomes[0], dict)
            result = first_outcomes[0]
            self.assertTrue(result["folder"].joinpath("README.md").is_file())
            self.assertFalse((output / TRANSACTION_NAME).exists())
            self.assertFalse(
                any(path.name.startswith(".nightmare-export-") for path in output.iterdir())
            )
            with zipfile.ZipFile(str(result["archive"])) as archive:
                self.assertIsNone(archive.testzip())
                self.assertEqual(
                    archive.read("README.md"),
                    (result["folder"] / "README.md").read_bytes(),
                )

            original_archive = result["archive"].read_bytes()
            with self.assertRaisesRegex(FileExistsError, "portable export already exists"):
                export_project(source, output)
            self.assertEqual(result["archive"].read_bytes(), original_archive)

