            server = ThreadingHTTPServer(("127.0.0.1", 0), PortableMockHandler)
            PortableMockHandler.request_count = 0
            thread = threading.Thread(target=server.serve_forever, daemon=True)
            thread.start()
            try:
                environment = os.environ.copy()
                environment.pop("PYTHONPATH", None)
                completed = subprocess.run(
                    [str(result["folder"] / "run.sh")]
                    + [
                        "--base-url",
                        "http://127.0.0.1:{}/v1".format(server.server_port),
                        "--model",
                        "portable-test-model",
                        "Answer a self-contained local test task",
                    ],
                    cwd=str(parent),
                    env=environment,
                    capture_output=True,
                    text=True,
                    timeout=15,
                    check=False,
                )
                extracted = parent / "zip-extracted"
                extracted.mkdir()
                with zipfile.ZipFile(str(result["archive"])) as archive:
                    archive.extractall(str(extracted))
                zip_completed = subprocess.run(
                    ["sh", str(extracted / "run.sh")]
                    + [
                        "--base-url",
                        "http://127.0.0.1:{}/v1".format(server.server_port),
                        "--model",
                        "portable-test-model",
                        "Answer a self-contained local test task",
                    ],
                    cwd=str(parent),
                    env=environment,
                    capture_output=True,
                    text=True,
                    timeout=15,
                    check=False,
                )
            finally:
                server.shutdown()
                server.server_close()
                thread.join(timeout=2)

            self.assertEqual(completed.returncode, 0, completed.stderr)
            self.assertIn("status: COMPLETED", completed.stdout)
            self.assertIn("Portable local mock answer", completed.stdout)
            self.assertEqual(zip_completed.returncode, 0, zip_completed.stderr)
            self.assertIn("status: COMPLETED", zip_completed.stdout)
            self.assertIn("Portable local mock answer", zip_completed.stdout)
            self.assertEqual(PortableMockHandler.request_count, 6)

